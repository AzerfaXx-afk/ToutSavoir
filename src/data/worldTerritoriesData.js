// Helper: Normalize strings for accent-insensitive search
export function normalizeSearchText(str) {
  if (!str) return '';
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
}

// Helper: Search and filter territories
export function searchTerritories(query = '', category = 'all', letter = null) {
  const cleanQ = normalizeSearchText(query);

  return WORLD_TERRITORIES.filter((item) => {
    // 1. Category Filter
    if (category === 'countries' && item.type !== 'country') return false;
    if (category === 'islands' && item.type !== 'island' && item.type !== 'drom-com') return false;

    // 2. Letter Filter
    if (letter && letter !== 'all') {
      const firstChar = normalizeSearchText(item.name).charAt(0).toUpperCase();
      if (firstChar !== letter.toUpperCase()) return false;
    }

    // 3. Text Query Search
    if (!cleanQ) return true;

    const normName = normalizeSearchText(item.name);
    const normRaw = normalizeSearchText(item.rawName);
    const normSovereign = normalizeSearchText(item.sovereign);
    const normCapital = normalizeSearchText(item.capital || '');
    const normContinent = normalizeSearchText(item.continent);
    const iso2 = (item.iso2 || '').toLowerCase();
    const iso3 = (item.iso3 || '').toLowerCase();

    return (
      normName.includes(cleanQ) ||
      normRaw.includes(cleanQ) ||
      normSovereign.includes(cleanQ) ||
      normCapital.includes(cleanQ) ||
      normContinent.includes(cleanQ) ||
      iso2 === cleanQ ||
      iso3 === cleanQ
    );
  });
}

// Helper: Group territories alphabetically
export function getAlphabetGroupedTerritories(list) {
  const groups = {};
  list.forEach((item) => {
    const firstLetter = normalizeSearchText(item.name).charAt(0).toUpperCase() || '#';
    if (!groups[firstLetter]) groups[firstLetter] = [];
    groups[firstLetter].push(item);
  });
  return groups;
}

